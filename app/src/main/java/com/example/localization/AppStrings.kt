private val Context.dataStore by preferencesDataStore(name = "helper_adda_prefs")

enum class AppLanguage(val code: String, val nativeLabel: String) {
    ENGLISH("EN", "English"),
    HINDI("HI", "हिंदी"),
    BENGALI("BN", "বাংলা");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code == code } ?: ENGLISH
    }
}

class LanguagePreferences(private val context: Context) {
    private val langKey = stringPreferencesKey("app_language")

    val languageFlow: Flow<AppLanguage> = context.dataStore.data.map { prefs ->
        AppLanguage.fromCode(prefs[langKey])
    }

    suspend fun setLanguage(language: AppLanguage) {
        context.dataStore.edit { prefs ->
            prefs[langKey] = language.code
        }
    }
}

